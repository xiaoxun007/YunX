// fork 分发用固定 release 签名：CI runner 不同会导致 debug keystore 每次变化、
// 跨版本无法覆盖安装。这里读取随仓库公开的 keystore.properties（fork 专用，非官方发布密钥）。
// 注意：用 import 的 Properties 而非 java.util.Properties —— 脚本顶层 java 已被 Gradle 的
// java 扩展遮蔽（java.util 会解析成 JavaPluginExtension.util 而编译失败）。
// 上游 #125 改为从 GitHub Secrets 注入证书；fork 仍走随仓库公开的 keystore.properties（gh-n 系列需要稳定可覆盖签名）。
val keystoreProperties = Properties().apply {
    runCatching { load(file("keystore.properties").inputStream()) }
}

android {
    namespace = "com.yunx.app"
    compileSdk = 36

    defaultConfig {
        applicationId = "com.yunx.app"
        // minSdk 24：AGP 8.13 的 D8 在 minSdk < 24 时必须脱糖接口静态方法，它把接口的 $default 桥方法
        // （如 RowScope.weight$default）搬进 $-CC 伴生类，却不改写第三方库字节码里的调用点，
        // 未混淆（debug）的包渲染 README 表格时必崩 NoSuchMethodError；24 起系统原生支持，不再脱糖。
        // 原因与实测证据见 Agent.md §3.11，勿降回 23。
        minSdk = 24
        targetSdk = 34
        // 与上游 CYQawa/YunX 版本号对齐；fork 构建在 versionName 后加 "-gh<n>" 后缀以区分。
        // 上游 1.3.0（#178~#196，深链接/多账号/B站/小红书/抖音等）已合入；fork 后缀随主线重计。
        // 1.3.0-gh1 = 41（merge 上游 1.3.0）；1.3.0-gh2 = 42（merge 上游 #202/#204/#206/#208 + 公告弹窗移除）。
        versionCode = 42
        versionName = "1.3.0-gh2"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        getByName("debug") {
            storeFile = file("../debug.keystore")
            storePassword = "android"
            keyAlias = "androiddebugkey"
            keyPassword = "android"
        }
        // 固定 release 签名：跨版本可覆盖安装（仅当 keystore.properties 存在时配置，
        // 本地未配置时 release 变体回退到 debug 签名，不阻断构建）。
        if (keystoreProperties.size > 0) {
            create("release") {
                storeFile = file(keystoreProperties["storeFile"] as String)
                storePassword = keystoreProperties["storePassword"] as String
                keyAlias = keystoreProperties["keyAlias"] as String
                keyPassword = keystoreProperties["keyPassword"] as String
            }
        }
    }

    buildTypes {
        debug {
            signingConfig = signingConfigs.getByName("debug")
        }
        // Release 变体：R8 代码混淆 + 资源压缩瘦身（未使用的代码/资源裁剪）；
        // 用固定 release 签名（见上），跨版本可覆盖安装。
        // R8 可能误删反射/序列化类，已在 proguard-rules.pro 补 Room 等 keep 规则。
        getByName("release") {
            isMinifyEnabled = true
            isShrinkResources = true
            signingConfig = signingConfigs.findByName("release") ?: signingConfigs.getByName("debug")
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
        }
    }

    buildFeatures {
        compose = true
    }

    testOptions {
        // 单元测试中 android.util.Log 等桩方法返回默认值（否则一调用就抛 "Stub!"）
        unitTests.isReturnDefaultValues = true
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    kotlin {
        compilerOptions {
            jvmTarget.set(org.jetbrains.kotlin.gradle.dsl.JvmTarget.fromTarget("17"))
        }
    }
}

